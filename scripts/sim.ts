/**
 * Balance simulation. Run with `npm run sim` (add `-- --quick` for a fast, noisier pass).
 * Prints a report and writes it to reports/balance.md.
 *
 *   --matches N   AI-vs-AI matches with random markets   (default 1500)
 *   --tier N      matches per cell of the tier matrix    (default 100)
 *   --samples N   Monte Carlo hands per trait measurement (default 1000)
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { balance, ctx, playerList } from '../src/data';
import { bestPlay, chooseDiscards } from '../src/engine/ai';
import { fullDeck } from '../src/engine/cards';
import { bandIndexOf } from '../src/engine/market';
import { measureTrait, powerFromStats, powerScore, suggestPrice } from '../src/engine/power';
import { Rng } from '../src/engine/rng';
import { MatchLog, simulateMatch } from '../src/engine/simulate';
import { describePlayerTrait, traitModifiers } from '../src/engine/traits';
import type { CardId, HandId, Position, Side, Squad, Trait } from '../src/engine/types';
import { HAND_IDS, POSITIONS } from '../src/engine/types';

const argv = process.argv.slice(2);
const quick = argv.includes('--quick');
const arg = (name: string, dflt: number) => {
  const i = argv.indexOf(`--${name}`);
  return i >= 0 ? Number(argv[i + 1]) : dflt;
};
const MATCHES = arg('matches', quick ? 200 : 1500);
const TIER = arg('tier', quick ? 20 : 100);
const SAMPLES = arg('samples', quick ? 300 : 1000);

const lines: string[] = [];
const out = (s = '') => {
  lines.push(s);
  console.log(s);
};
const pct = (x: number, d = 1) => (x * 100).toFixed(d) + '%';
const f = (x: number, d = 1) => x.toFixed(d);
function table(headers: string[], rows: (string | number)[][]) {
  out('| ' + headers.join(' | ') + ' |');
  out('|' + headers.map(() => '---').join('|') + '|');
  for (const r of rows) out('| ' + r.join(' | ') + ' |');
  out();
}
const t0 = Date.now();
const progress = (m: string) => console.error(`[${((Date.now() - t0) / 1000).toFixed(0)}s] ${m}`);

out('# Balance report');
out();
out(`Generated by \`npm run sim\` (${MATCHES} matches, ${SAMPLES} hands per trait measurement, ${TIER} matches per tier cell).`);
out();

// ---------------------------------------------------------------------------------------------
// 1. Hand distribution under the AI strategy (no traits)
progress('hand distribution');
{
  const N = quick ? 4000 : 20000;
  const counts: Record<string, number> = {};
  let total = 0;
  const rng = new Rng(777);
  for (let i = 0; i < N; i++) {
    const deck = rng.shuffle(fullDeck());
    let hand: CardId[] = deck.splice(0, balance.handSize);
    let discards = balance.discards;
    let best;
    for (;;) {
      best = bestPlay(ctx, hand, { activeTrait: null, keeperTrait: null, discardsLeft: discards });
      const toss = chooseDiscards(ctx, hand, best.result, discards);
      if (!toss.length) break;
      const fresh = deck.splice(0, toss.length);
      let k = 0;
      hand = hand.flatMap((c) => (toss.includes(c) ? (k < fresh.length ? [fresh[k++]] : []) : [c]));
      discards -= toss.length;
    }
    counts[best.result.hand] = (counts[best.result.hand] ?? 0) + 1;
    total += best.result.score;
  }
  out('## 1. Hand frequencies (AI plays the best 1-5 card subset after smart discards, no traits)');
  out();
  table(
    ['Hand', 'Frequency', 'Base score'],
    HAND_IDS.map((h) => [
      balance.hands[h].label,
      pct((counts[h] ?? 0) / N, 2),
      balance.hands[h].chips * balance.hands[h].mult,
    ]),
  );
  out(`Average duel score without traits: **${f(total / N)}**`);
  out();
}

// ---------------------------------------------------------------------------------------------
// 2. Trait templates: uplift at default / min / max parameters
progress('trait templates');
{
  out('## 2. Trait templates (average duel-score uplift vs. no trait, while the player is active)');
  out();
  const rows: (string | number)[][] = [];
  for (const tpl of ctx.catalog.filter((t) => t.enabled)) {
    const pos: Position = tpl.allowedPositions.includes('MID') ? 'MID' : tpl.allowedPositions[0];
    const base: Trait = { type: tpl.id, params: {} };
    for (const [k, def] of Object.entries(tpl.params)) base.params[k] = structuredClone(def.default);
    const at = (override: Record<string, unknown>): string => {
      const tr = { type: tpl.id, params: { ...base.params, ...override } };
      return pct(measureTrait(ctx, tr, pos, SAMPLES).uplift, 0);
    };
    const numeric = Object.entries(tpl.params).filter(([, d]) => d.type === 'number') as [string, { min: number; max: number }][];
    const first = numeric[numeric.length - 1];
    const lo = first ? at({ [first[0]]: first[1].min }) : '-';
    const mid = at({});
    const hi = first ? at({ [first[0]]: first[1].max }) : '-';
    rows.push([tpl.id, pos, first ? first[0] : '-', lo, mid, hi]);
  }
  table(['Template', 'Measured at', 'Varied param', 'Uplift @min', 'Uplift @default', 'Uplift @max'], rows);
}

// ---------------------------------------------------------------------------------------------
// 3. Players
progress('players');
const power = new Map<string, number>();
{
  out('## 3. Seed players: power score and price');
  out();
  const rows: (string | number)[][] = [];
  for (const p of playerList) {
    const stats = measureTrait(ctx, p.trait, p.position, SAMPLES);
    const pw = powerFromStats(ctx, p.position, p.trait.type, stats);
    power.set(p.id, pw);
    rows.push([
      p.id,
      `${p.firstName} ${p.lastName}`,
      p.position,
      describePlayerTrait(p, ctx),
      pct(stats.uplift, 0),
      pct(stats.winProb, 1),
      f(pw, 3),
      `$${p.price}`,
      `$${suggestPrice(balance, pw)}`,
    ]);
  }
  table(['id', 'Name', 'Pos', 'Trait', 'Score uplift', 'Duel win prob vs. no-trait', 'Power (price-weighted)', 'Price', 'Suggested'], rows);
}

// ---------------------------------------------------------------------------------------------
// 4. Matches with random markets and random (rule-abiding) squads
progress('matches');
const logs: MatchLog[] = [];
for (let i = 0; i < MATCHES; i++) {
  logs.push(simulateMatch(ctx, 1000 + i));
  if (i % 250 === 249) progress(`  ${i + 1}/${MATCHES} matches`);
}
{
  out('## 4. AI vs AI matches (random markets, random valid squads)');
  out();
  let winsA = 0, winsB = 0, draws = 0, goalsA = 0, goalsB = 0, shots = 0, goals = 0;
  let resolved = 0, ties = 0, totalDuels = 0, reshuffleMatches = 0, reshuffleHalves = 0, halves = 0;
  const nodeCount: Record<number, number> = { '-1': 0, '0': 0, '1': 0 };
  const handCount: Record<string, number> = {};
  let spent = 0;
  const maxDuels = [0, 0];
  for (const l of logs) {
    const A = l.final.sides.A.goals, B = l.final.sides.B.goals;
    goalsA += A; goalsB += B;
    if (A > B) winsA++; else if (B > A) winsB++; else draws++;
    shots += l.shots.length; goals += l.shots.filter((s) => s.goal).length;
    for (const d of l.duels) {
      totalDuels++;
      if (d.winner === 'tie') ties++; else { resolved++; nodeCount[d.node]++; }
      for (const s of ['A', 'B'] as const) handCount[d.sides[s].hand] = (handCount[d.sides[s].hand] ?? 0) + 1;
    }
    if (l.reshuffles > 0) reshuffleMatches++;
    halves += 2;
    for (const side of ['A', 'B'] as const)
      spent += POSITIONS.reduce((s, p) => s + (l.final.sides[side].squad[p] ? ctx.players[l.final.sides[side].squad[p]!].price : 0), 0);
    maxDuels[0] = Math.max(maxDuels[0], l.duelsPerHalf[0]);
    maxDuels[1] = Math.max(maxDuels[1], l.duelsPerHalf[1]);
  }
  reshuffleHalves = logs.reduce((s, l) => s + l.reshuffles, 0);
  const n = logs.length;
  table(
    ['Metric', 'Value'],
    [
      ['Matches', n],
      ['Host (A) win / draw / guest (B) win', `${pct(winsA / n)} / ${pct(draws / n)} / ${pct(winsB / n)}`],
      ['Goals per match (A + B)', `${f(goalsA / n, 2)} + ${f(goalsB / n, 2)} = ${f((goalsA + goalsB) / n, 2)}`],
      ['Shots per match / goal rate', `${f(shots / n, 2)} / ${pct(goals / Math.max(1, shots))} (random picks => 66.7%)`],
      ['Duels per match incl. ties', f(totalDuels / n, 1)],
      ['Tie rate (replayed duels)', pct(ties / totalDuels)],
      ['Resolved duels at A-defense node (-1) / midfield (0) / A-attack node (+1)', `${pct(nodeCount[-1] / resolved)} / ${pct(nodeCount[0] / resolved)} / ${pct(nodeCount[1] / resolved)}`],
      ['Longest half seen (duels incl. ties)', `${maxDuels[0]} / ${maxDuels[1]}`],
      ['Matches where a deck had to be recycled (played pile shuffled back in)', `${pct(reshuffleMatches / n, 2)}`],
      ['Recycle events per 100 halves', f((reshuffleHalves / halves) * 100, 2)],
      ['Average squad spend', `$${f(spent / (2 * n))} of $${balance.budget}`],
    ],
  );
  out('Hands played in duels:');
  out();
  const totalHands = Object.values(handCount).reduce((a, b) => a + b, 0);
  table(['Hand', 'Share'], HAND_IDS.map((h) => [balance.hands[h].label, pct((handCount[h] ?? 0) / totalHands, 2)]));

  // Per player / per template duel win rate while active.
  type Agg = { duels: number; wins: number; losses: number; score: number; matches: number; matchPts: number };
  const mk = (): Agg => ({ duels: 0, wins: 0, losses: 0, score: 0, matches: 0, matchPts: 0 });
  const byPlayer = new Map<string, Agg>();
  const get = (id: string) => byPlayer.get(id) ?? (byPlayer.set(id, mk()), byPlayer.get(id)!);
  for (const l of logs) {
    for (const d of l.duels) {
      for (const side of ['A', 'B'] as const) {
        const ids = new Set<string>();
        const a = d.sides[side];
        // Field player active at this node. Keepers count in every duel of their team.
        if (a.active) ids.add(a.active);
        if (a.keeper) ids.add(a.keeper);
        for (const id of ids) {
          const g = get(id);
          g.duels++;
          g.score += a.score;
          if (d.winner === side) g.wins++;
          else if (d.winner !== 'tie') g.losses++;
        }
      }
    }
    for (const side of ['A', 'B'] as const) {
      const opp: Side = side === 'A' ? 'B' : 'A';
      const my = l.final.sides[side].goals, their = l.final.sides[opp].goals;
      const pts = my > their ? 1 : my === their ? 0.5 : 0;
      for (const pos of POSITIONS) {
        const id = l.final.sides[side].squad[pos];
        if (!id) continue;
        const g = get(id);
        g.matches++;
        g.matchPts += pts;
      }
    }
  }
  out('### Per player (duel win rate while active; keepers count in all duels of their team)');
  out();
  const rows = playerList
    .map((p) => {
      const g = byPlayer.get(p.id) ?? mk();
      const wr = g.wins / Math.max(1, g.wins + g.losses);
      return { p, g, wr };
    })
    .sort((a, b) => b.wr - a.wr);
  table(
    ['id', 'Pos', 'Trait', 'Price', 'Power', 'Duels', 'Duel win rate', 'Avg score', 'Match points rate'],
    rows.map(({ p, g, wr }) => [
      p.id,
      p.position,
      p.trait.type,
      `$${p.price}`,
      f(power.get(p.id) ?? 0, 3),
      g.duels,
      pct(wr),
      f(g.score / Math.max(1, g.duels)),
      pct(g.matchPts / Math.max(1, g.matches)),
    ]),
  );

  const byTpl = new Map<string, { wins: number; losses: number; duels: number; price: number; n: number }>();
  for (const { p, g } of rows) {
    const a = byTpl.get(p.trait.type) ?? { wins: 0, losses: 0, duels: 0, price: 0, n: 0 };
    a.wins += g.wins; a.losses += g.losses; a.duels += g.duels; a.price += p.price; a.n++;
    byTpl.set(p.trait.type, a);
  }
  out('### Per trait template');
  out();
  table(
    ['Template', 'Players', 'Avg price', 'Duels', 'Duel win rate'],
    [...byTpl.entries()]
      .sort((a, b) => b[1].wins / (b[1].wins + b[1].losses) - a[1].wins / (a[1].wins + a[1].losses))
      .map(([id, a]) => [id, a.n, `$${f(a.price / a.n, 0)}`, a.duels, pct(a.wins / Math.max(1, a.wins + a.losses))]),
  );

  // Price vs win rate by price band.
  const byBand = balance.priceBands.map(() => ({ wins: 0, losses: 0 }));
  for (const { p, g } of rows.filter((r) => r.p.position !== 'GK')) {
    const b = bandIndexOf(balance, p.price);
    byBand[b].wins += g.wins; byBand[b].losses += g.losses;
  }
  out('### Duel win rate by price band (field players)');
  out();
  table(['Band', 'Duel win rate'], byBand.map((b, i) => [balance.priceBands[i].id, pct(b.wins / Math.max(1, b.wins + b.losses))]));
  const gkBand = balance.priceBands.map(() => ({ wins: 0, losses: 0 }));
  for (const { p, g } of rows.filter((r) => r.p.position === 'GK')) {
    const b = bandIndexOf(balance, p.price);
    gkBand[b].wins += g.wins; gkBand[b].losses += g.losses;
  }
  out('### Duel win rate by price band (goalkeepers)');
  out();
  table(['Band', 'Duel win rate'], gkBand.map((b, i) => [balance.priceBands[i].id, pct(b.wins / Math.max(1, b.wins + b.losses))]));
}

// ---------------------------------------------------------------------------------------------
// 5. Tier matrix: expected duel win probability between average squads of each price band
progress('tier matrix');
{
  out('## 5. Duel win probability by squad tier (row beats column)');
  out();
  out('Each squad takes one random player per position from the given price band. Ties are excluded.');
  out();
  const byPosBand = (pos: Position, band: number) => playerList.filter((p) => p.position === pos && bandIndexOf(balance, p.price) === band);
  const rng = new Rng(4242);
  const squadOf = (band: number): Squad => {
    const s: Squad = {};
    for (const pos of POSITIONS) {
      const pool = byPosBand(pos, band);
      if (pool.length) s[pos] = rng.pick(pool).id;
    }
    return s;
  };
  const bands = balance.priceBands.map((b) => b.id);
  const rows: (string | number)[][] = [];
  for (let i = 0; i < bands.length; i++) {
    const row: (string | number)[] = [bands[i]];
    for (let j = 0; j < bands.length; j++) {
      let w = 0, l = 0;
      for (let k = 0; k < TIER; k++) {
        const log = simulateMatch(ctx, 90000 + i * 1000 + j * 100 + k, { A: squadOf(i), B: squadOf(j) });
        for (const d of log.duels) {
          if (d.winner === 'A') w++;
          else if (d.winner === 'B') l++;
        }
      }
      row.push(pct(w / Math.max(1, w + l)));
    }
    rows.push(row);
  }
  table(['row \\ col', ...bands], rows);
}

// ---------------------------------------------------------------------------------------------
// 6. Budget-valid spending strategies
progress('strategies');
{
  out(`## 6. Spending strategies under the $${balance.budget} budget (row beats column, duel win rate)`);
  out();
  out('Each strategy assigns a price band to GK / DEF / MID / FWD; squads are drawn at random from those bands and must fit the budget.');
  out();
  const strategies: [string, number[]][] = [
    ['balanced (mid x4)', [1, 1, 1, 1]],
    ['legend GK + 3 rookies', [3, 0, 0, 0]],
    ['legend DEF + 3 rookies', [0, 3, 0, 0]],
    ['legend MID + 3 rookies', [0, 0, 3, 0]],
    ['legend FWD + 3 rookies', [0, 0, 0, 3]],
    ['star MID+FWD + 2 rookies', [0, 0, 2, 2]],
    ['star GK+MID + 2 rookies', [2, 0, 2, 0]],
    ['star MID + mid DEF/FWD + rookie GK', [0, 1, 2, 1]],
    ['all rookies', [0, 0, 0, 0]],
  ];
  const rng = new Rng(2024);
  const squadFor = (bands: number[]): Squad => {
    for (let attempt = 0; attempt < 200; attempt++) {
      const squad: Squad = {};
      let cost = 0;
      POSITIONS.forEach((pos, i) => {
        const pool = playerList.filter((p) => p.position === pos && bandIndexOf(balance, p.price) === bands[i]);
        const pick = rng.pick(pool);
        squad[pos] = pick.id;
        cost += pick.price;
      });
      if (cost <= balance.budget) return squad;
    }
    throw new Error('Could not build a budget-valid squad for ' + bands.join());
  };
  const avgCost = strategies.map(([, b]) => {
    let c = 0;
    for (let i = 0; i < 40; i++) {
      const sq = squadFor(b);
      c += POSITIONS.reduce((sum, pos) => sum + ctx.players[sq[pos]!].price, 0);
    }
    return c / 40;
  });
  const n = strategies.length;
  const grid: number[][] = Array.from({ length: n }, () => Array(n).fill(0.5));
  for (let i = 0; i < n; i++)
    for (let j = 0; j < n; j++) {
      let w = 0,
        l = 0;
      for (let k = 0; k < TIER; k++) {
        const log = simulateMatch(ctx, 500000 + i * 10000 + j * 100 + k, {
          A: squadFor(strategies[i][1]),
          B: squadFor(strategies[j][1]),
        });
        for (const d of log.duels) {
          if (d.winner === 'A') w++;
          else if (d.winner === 'B') l++;
        }
      }
      grid[i][j] = w / Math.max(1, w + l);
    }
  table(
    ['Strategy', 'avg cost', ...strategies.map((_, i) => `S${i + 1}`), 'average'],
    strategies.map(([name], i) => [
      `S${i + 1} ${name}`,
      `$${f(avgCost[i], 0)}`,
      ...grid[i].map((v) => pct(v, 0)),
      pct(grid[i].reduce((a, b) => a + b, 0) / n, 1),
    ]),
  );
}

