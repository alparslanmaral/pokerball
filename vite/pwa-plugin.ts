import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Plugin } from 'vite';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC_PRECACHE = ['manifest.webmanifest', 'icons/icon.svg', 'icons/icon-192.png', 'icons/icon-512.png', 'icons/icon-maskable-512.png', 'icons/apple-touch-icon.png'];

/**
 * Emits a small service worker (sw.js) at build time: precaches the app shell (all built files and the
 * PWA icons) so the game opens offline, caches player portraits on first use, and versions the cache by
 * content hash so every deploy replaces the old one. Build only: nothing runs in `vite dev`.
 */
export function pwaPlugin(): Plugin {
  return {
    name: 'poker-pitch-pwa',
    apply: 'build',
    enforce: 'post',
    generateBundle(_options, bundle) {
      const files = new Set<string>(['./']);
      const hash = createHash('sha1');
      for (const [name, chunk] of Object.entries(bundle)) {
        files.add(name);
        hash.update(name);
        if (chunk.type === 'asset') hash.update(typeof chunk.source === 'string' ? chunk.source : Buffer.from(chunk.source));
      }
      for (const f of PUBLIC_PRECACHE) {
        files.add(f);
        hash.update(readFileSync(resolve(root, 'public', f)));
      }
      const version = hash.digest('hex').slice(0, 10);
      const sw = `/* Generated by vite/pwa-plugin.ts — do not edit. */
const VERSION = ${JSON.stringify(version)};
const CACHE = 'poker-pitch-' + VERSION;
const IMAGES = 'poker-pitch-images';
const PRECACHE = ${JSON.stringify([...files])};
const scope = self.registration.scope;
const abs = (p) => new URL(p, scope).href;
// ignoreVary: static hosts may send a Vary: Origin header, which made module scripts (CORS mode) miss the cache.
const MATCH = { ignoreVary: true };

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE.map(abs)))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('poker-pitch-') && k !== CACHE && k !== IMAGES).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // signalling/STUN traffic is never touched

  // Page loads: network first (fresh deploys), fall back to the cached shell when offline.
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req).catch(() => caches.match(abs('./'), MATCH).then((r) => r || caches.match(abs('index.html'), MATCH))),
    );
    return;
  }

  // Player portraits live in public/players and change without a rebuild: stale-while-revalidate.
  if (url.pathname.includes('/players/')) {
    event.respondWith(
      caches.open(IMAGES).then(async (cache) => {
        const cached = await cache.match(req, MATCH);
        const network = fetch(req)
          .then((res) => {
            if (res.ok) cache.put(req, res.clone());
            return res;
          })
          .catch(() => cached);
        return cached || network;
      }),
    );
    return;
  }

  // Built assets are content-hashed: cache first.
  event.respondWith(
    caches.match(req, MATCH).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) caches.open(CACHE).then((c) => c.put(req, res.clone()));
          return res;
        }),
    ),
  );
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: sw });
    },
  };
}
